"""Production adapter for frozen L with a lightweight J fallback."""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

import pandas as pd

from candidate_l_spectral import MODEL_TYPE, VERSION, predict

J_NAME = "candidate_j_v1_1_regime_aware"

def build_j(cycle, observations, store):
    import candidate_j_shadow as cjs
    from cycle_predictions import _build_candidate_j_official_predictions
    model = store.load_model_by_name(J_NAME)
    artifact = cjs.load_artifact(str(model["artifact_uri"]))
    predictions, g_model, g_predictions = _build_candidate_j_official_predictions(
        cycle, model, artifact, observations, store)
    return model, predictions, [(g_model, g_predictions)]


def build_official_predictions(cycle, model, observations, store):
    from cycle_predictions import CyclePrediction, validate_predictions, _now_iso, _ts, _warn
    if model.get("model_type") != MODEL_TYPE or model.get("is_active") is not True:
        raise ValueError("Candidate L must be the active registered model")
    try:
        targets = pd.DataFrame([{"station_id": t.station_id, "target_at": t.target_at,
                                 "horizon_minutes": t.horizon_minutes} for t in cycle.targets])
        frame, manifest = predict(observations, cycle.data_cutoff, targets)
        by_target = {(str(r.station_id), _ts(r.target_at)): r.prediction for r in frame.itertuples()}
        predictions = [CyclePrediction(
            cycle_id=cycle.cycle_id, model_id=str(model["model_id"]), station_id=t.station_id,
            target_at=t.target_at, horizon_minutes=t.horizon_minutes,
            prediction=float(by_target[(t.station_id, _ts(t.target_at))]),
            trace={"candidate": VERSION, "path": "l", "data_cutoff": cycle.data_cutoff,
                   "train_rows": manifest["stations"][t.station_id]["rows"],
                   "weights_sha256": manifest["weights_sha256"]}) for t in cycle.targets]
        validate_predictions(cycle, predictions)
        manifest.update(cycle_id=cycle.cycle_id, fitted_at=_now_iso(), git_commit=os.getenv("GITHUB_SHA"))
        folder = Path(os.getenv("CANDIDATE_L_REFIT_DIR", ".candidate_l_refits"))
        folder.mkdir(parents=True, exist_ok=True)
        filename = hashlib.sha256(cycle.cycle_id.encode()).hexdigest() + ".json"
        (folder / filename).write_text(json.dumps(manifest, indent=2))
        model["trained_until"] = max(s["training_end"] for s in manifest["stations"].values())
        model["created_at"] = manifest["fitted_at"]
        if manifest["git_commit"]:
            model["git_commit"] = manifest["git_commit"]
        store.persist_l_refit(model, manifest)
    except Exception as exc:
        _warn("Candidate L failed; using registered J fallback", f"{type(exc).__name__}: {exc}")
        j_model, predictions, dependencies = build_j(cycle, observations, store)
        validate_predictions(cycle, predictions)
        # run_official_cycle passes this same object through to submission. Never
        # claim J's predictions were generated by L.
        model.clear()
        model.update(j_model)
        return predictions, dependencies

    # L is the official path. Expensive K shadow comparison belongs in its own
    # workflow and must not consume the submission runner's minute budget.
    return predictions, []
